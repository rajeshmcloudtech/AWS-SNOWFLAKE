
-- PROCEDURE 

CREATE OR REPLACE PROCEDURE SP_DIM_CUSTOMER(TABLE_NAME VARCHAR(100))
RETURNS VARCHAR(2000)
LANGUAGE SQL 
AS 
DECLARE 
V_START_TIME TIMESTAMP;
V_END_TIME TIMESTAMP;
V_SOURCE_TABLE_NAME VARCHAR(200);
V_TARGET_TABLE_NAME VARCHAR(200);
V_SOURCE_RECORD_COUNT NUMBER(10);
V_TARGET_RECORD_COUNT NUMBER(10);
V_QUERY VARCHAR(2000);
BEGIN 

-- PROCEDURE START TIME
LET V_START_TIME_PROC:=CURRENT_TIMESTAMP();

-- STEP 1 LOAD DATA INTO FILES AND PRE_STAGE_TABLE
-- AND HERE LOADING DATA IN THE AWS S3 BUCKET
V_START_TIME:=CURRENT_TIMESTAMP();
DESC TABLE SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.CUSTOMER;
V_SOURCE_TABLE_NAME:='SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.'||TABLE_NAME;

SELECT COUNT(1) INTO V_SOURCE_RECORD_COUNT FROM IDENTIFIER(:V_SOURCE_TABLE_NAME);
LET FILE_TIMESTAMP:=TO_CHAR(CURRENT_TIMESTAMP(),'YYYYMMDDHH24MISS');

LET COPY_SQL :=
    'COPY INTO @AZUREDWH_ETL.PUBLIC.S3_IMPORT_STAGE/SOURCE_FILES/DIM_'
    || TABLE_NAME || '_' || FILE_TIMESTAMP || '.TXT '
    || 'FROM (SELECT * FROM IDENTIFIER(?)) '
    || 'FILE_FORMAT = (TYPE = CSV FIELD_DELIMITER = '','' COMPRESSION = NONE) '
    || 'HEADER = TRUE OVERWRITE = TRUE MAX_FILE_SIZE = 5368709120';

EXECUTE IMMEDIATE COPY_SQL USING (V_SOURCE_TABLE_NAME);

-- IMPORTING DATA FILES FROM AWS S3 TO EXPORT_S3_STAGE 
-- COPING DATA FILES FROM EXPORT_S3_STAGE TO PRE_STAGE_TABLE
V_QUERY := 'COPY INTO AZUREDWH_ETL.PUBLIC.PRE_STAGE_' || TABLE_NAME || 
               ' FROM @AZUREDWH_ETL.PUBLIC.EXPORT_S3_STAGE' ||
               ' PATTERN = ''.*DIM_' || TABLE_NAME || '_.*''' ||
               ' FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_DELIMITER = '','')';

EXECUTE IMMEDIATE V_QUERY;
V_TARGET_TABLE_NAME:='AZUREDWH_ETL.PUBLIC.PRE_STAGE_'||TABLE_NAME;

SELECT COUNT(1) INTO V_TARGET_RECORD_COUNT FROM IDENTIFIER(:V_TARGET_TABLE_NAME);

V_END_TIME:=CURRENT_TIMESTAMP();

-- UPDAING DATA IN AUDIT_TABLE 1

INSERT INTO AZUREDWH_ETL.PUBLIC.AUDIT_LOG_INFORMATION(SOURCE_TABLE_NAME,TARGET_TABLE_NAME,SOURCE_RECORD_COUNT,TARGET_RECORD_COUNT,START_TIME,END_TIME,STATUS,REASON_FOR_FAILURE) VALUES 
(:V_SOURCE_TABLE_NAME,:V_TARGET_TABLE_NAME,:V_SOURCE_RECORD_COUNT,:V_TARGET_RECORD_COUNT,:V_START_TIME,:V_END_TIME,'SUCCESS',NULL);



-- COPYING DATA FROM PRE_STAGE TO STAGE_TABLE BY ADDING EXTRA COLUNM iNSERT_GMT_TIMESTAMP

V_START_TIME:=CURRENT_TIMESTAMP();
V_SOURCE_TABLE_NAME:='AZUREDWH_ETL.PUBLIC.PRE_STAGE_'||TABLE_NAME;

-- TRUNCATING DATA FROM  STAGE_TABLE

SELECT COUNT(1) INTO V_SOURCE_RECORD_COUNT FROM IDENTIFIER(:V_SOURCE_TABLE_NAME);
 V_QUERY:='TRUNCATE TABLE STAGE_'||TABLE_NAME;
EXECUTE IMMEDIATE V_QUERY;

-- INSERT DATA INTO STAGE_TABLE 
V_QUERY:='INSERT INTO STAGE_'||TABLE_NAME||' SELECT P.*, CURRENT_TIMESTAMP() AS INSERT_GMT_TIMESTAMP FROM PRE_STAGE_'||TABLE_NAME||' P';
EXECUTE IMMEDIATE V_QUERY;
V_TARGET_TABLE_NAME:='AZUREDWH_ETL.PUBLIC.STAGE_'||TABLE_NAME;

SELECT COUNT(1) INTO V_TARGET_RECORD_COUNT FROM IDENTIFIER(:V_TARGET_TABLE_NAME);

V_END_TIME:=CURRENT_TIMESTAMP();

-- UPDATING DATA INTO AUDIT TABLE 2
INSERT INTO AZUREDWH_ETL.PUBLIC.AUDIT_LOG_INFORMATION(SOURCE_TABLE_NAME,TARGET_TABLE_NAME,SOURCE_RECORD_COUNT,TARGET_RECORD_COUNT,START_TIME,END_TIME,STATUS,REASON_FOR_FAILURE) VALUES 
(:V_SOURCE_TABLE_NAME,:V_TARGET_TABLE_NAME,:V_SOURCE_RECORD_COUNT,:V_TARGET_RECORD_COUNT,:V_START_TIME,:V_END_TIME,'SUCCESS',NULL);


-- STEP 2 LOADING DATA FROM STAGE_TABLE TO DIM_TABLE 

V_START_TIME:=CURRENT_TIMESTAMP();
V_SOURCE_TABLE_NAME:='AZUREDWH_ETL.PUBLIC.STAGE_'||TABLE_NAME;

SELECT COUNT(1) INTO V_SOURCE_RECORD_COUNT FROM IDENTIFIER(:V_SOURCE_TABLE_NAME);

-- DELETE DATA FROM DIM_TABLE
V_QUERY:= 'DELETE FROM DIM_'||TABLE_NAME;
EXECUTE IMMEDIATE V_QUERY;

-- INSERT DATA INTO DIM_TABLE FROM STAGE_TABLE
V_QUERY:='INSERT INTO DIM_'||TABLE_NAME||' SELECT S.*,CURRENT_TIMESTAMP() AS UPDATE_GMT_TIMESTAMP FROM STAGE_'||TABLE_NAME||' S';
EXECUTE IMMEDIATE V_QUERY;

V_TARGET_TABLE_NAME:='AZUREDWH_ETL.PUBLIC.DIM_'||TABLE_NAME;

SELECT COUNT(1) INTO V_TARGET_RECORD_COUNT FROM IDENTIFIER(:V_TARGET_TABLE_NAME);

V_END_TIME:=CURRENT_TIMESTAMP();

-- UPDATING DATA INTO AUDIT_TABLE 3
INSERT INTO AZUREDWH_ETL.PUBLIC.AUDIT_LOG_INFORMATION(SOURCE_TABLE_NAME,TARGET_TABLE_NAME,SOURCE_RECORD_COUNT,TARGET_RECORD_COUNT,START_TIME,END_TIME,STATUS,REASON_FOR_FAILURE) VALUES 
(:V_SOURCE_TABLE_NAME,:V_TARGET_TABLE_NAME,:V_SOURCE_RECORD_COUNT,:V_TARGET_RECORD_COUNT,:V_START_TIME,:V_END_TIME,'SUCCESS',NULL);

LET V_END_TIME_PROC:=CURRENT_TIMESTAMP();


RETURN 'Exported and loaded START_TIME_: ' ||V_START_TIME_PROC||' END_TIME: '||V_END_TIME_PROC;

-- COPYING STAGE FILES INTO ARCHIVE_STAGE

COPY FILES INTO @AZUREDWH_ETL.PUBLIC.ARCHIVE_STAGE FROM @AZUREDWH_ETL.PUBLIC.EXPORT_S3_STAGE
PATTERN='.*DIM_CUSTOMER_.*';

-- DELETING FILES FROM STAGE 

REMOVE @AZUREDWH_ETL.PUBLIC.EXPORT_S3_STAGE;

-- EXCEPTION 

EXCEPTION 
WHEN OTHER THEN 
LET V_ERROR_MESSAGE:=SQLERRM;
INSERT INTO AZUREDWH_ETL.PUBLIC.AUDIT_LOG_INFORMATION(SOURCE_TABLE_NAME,TARGET_TABLE_NAME,SOURCE_RECORD_COUNT,TARGET_RECORD_COUNT,START_TIME,END_TIME,STATUS,REASON_FOR_FAILURE) VALUES 
(:V_SOURCE_TABLE_NAME,:V_TARGET_TABLE_NAME,:V_SOURCE_RECORD_COUNT,:V_TARGET_RECORD_COUNT,:V_START_TIME,:V_END_TIME,'FAILED',:SQLERRM);

RETURN 'FAILED: '||V_ERROR_MESSAGE;

END;


CALL SP_DIM_CUSTOMER('CUSTOMER');


SELECT * FROM AUDIT_LOG_INFORMATION;





